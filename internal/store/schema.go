// schemaSteps PG 增量迁移步骤(版本号 → 单条 SQL,幂等:*IF NOT EXISTS*;单事务内逐条应用)。
//
// 为什么需要:baselinePG 只在**空库**跑(它建终态全表);对已存在的库(如生产在 v14)直接
// bump schemaVersion 会重跑基线 → `CREATE TABLE admins` 冲突。故 v15 起,新库走基线(直接是终态),
// 旧库走本表逐版递增。新库的表结构【必须】同时反映在 baselinePG(vx 终态)与对应 schemaSteps[vx]。
var schemaSteps = map[int64]string{
	15: `
CREATE TABLE IF NOT EXISTS channel_model_cost_ratios (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id bigint NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  model_name text NOT NULL,
  ratio      double precision NOT NULL,
  source     text NOT NULL DEFAULT 'plan',
  note       text NOT NULL DEFAULT '',
  created_at text NOT NULL,
  updated_at text NOT NULL,
  UNIQUE (channel_id, model_name)
);
CREATE INDEX IF NOT EXISTS idx_channel_model_cost_ratios_channel ON channel_model_cost_ratios (channel_id);
`,
	16: `
-- v16:官方价来源收敛到 commandcode 单来源(删除 opencode zen 来源)。
-- 先「改绑」再「删」:一批模型的官方价绑定落在 opencode 的点号 slug 上(gpt-5.6-sol),
-- 而 CC 用连字符(gpt-5-6-sol),不先改绑就删 zen 会让它们丢官方价。
-- 守卫 EXISTS(CC 连字符孪生):仅当 CC 确有该行才改 —— 不误伤 CC 本身用点号的 qwen(qwen3.6-plus)。
-- 两语句均幂等(改完再跑不再命中;无 zen 行则 DELETE 空操作)。
UPDATE models
   SET official_model_name = translate(official_model_name, '.', '-')
 WHERE official_model_name LIKE '%.%'
   AND EXISTS (
         SELECT 1 FROM official_prices c
          WHERE c.source = 'commandcode'
            AND c.provider = models.official_vendor
            AND c.model_name = translate(models.official_model_name, '.', '-'));
DELETE FROM official_prices WHERE source = 'opencode';
`,
}

// migrate 建 schema_migrations,并把库推进到 schemaVersion:
//   - 空库(MAX(version)=0)→ 跑 baselinePG(直接建终态全表);
//   - 已有库 → 从 MAX(version)+1 起逐条跑 schemaSteps(缺步骤即硬错,不静默跳版)。
//
// 全程单事务;成功后才写 schema_migrations 的版本行。
func migrate(db pdb) error {
	if _, err := db.Exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
		version    bigint PRIMARY KEY,
		applied_at text NOT NULL
	)`); err != nil {
		return err
	}
	var cur int64
	if err := db.QueryRow(`SELECT COALESCE(MAX(version), 0) FROM schema_migrations`).Scan(&cur); err != nil {
		return err
	}
	if cur >= schemaVersion {
		return nil
	}
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if cur == 0 {
		if _, err := tx.Exec(baselinePG); err != nil {
			return fmt.Errorf("apply baseline: %w", err)
		}
	} else {
		for v := cur + 1; v <= schemaVersion; v++ {
			stmt, ok := schemaSteps[v]
			if !ok {
				return fmt.Errorf("缺少迁移步骤 v%d(库在 v%d,目标 v%d)", v, cur, schemaVersion)
			}
			if _, err := tx.Exec(stmt); err != nil {
				return fmt.Errorf("apply migration v%d: %w", v, err)
			}
		}
	}
	if _, err := tx.Exec(`INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)`,
		schemaVersion, nowRFC3339()); err != nil {
		return err
	}
	return tx.Commit()
}
