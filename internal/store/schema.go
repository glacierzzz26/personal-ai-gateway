// 存储 = PostgreSQL。迁移模型:单一 PG 基线 + 版本号。
//
// 为什么不是把 SQLite 时期的 14 步逐条 port:生产/测试库都是**整库搬运**(cmd/gwmigrate),
// 没有 PG 历史需要重放;faithfully 重建 m0011 的 LIKE 回填、m0014 的表重建只是无谓的churn。
// 故 baselinePG 直接建出「m0014 终态」的表结构,并把版本号播成 14 —— 使 SchemaVersion()
// ( /healthz 的 schema 字段)与升级脚本的降级护栏**语义不变**(后续 PG 迁移从 15 起追加)。
//
// 与 SQLite 时期的类型映射(刻意最小改动,见 DESIGN.md):
//   - 时间戳一律 text(UTC RFC3339Nano),不转 timestamptz —— 导入是逐列原样搬运;
//   - 布尔一律 bigint 0/1(b2i),不转 boolean —— 扫描侧不改成 *bool;
//   - JSON 一律 text(encodeJSON/decode*);
//   - 金额 REAL → double precision(**不用 numeric**:numeric 扫不进 *float64);
//   - 所有整数列一律 bigint(与 SQLite 的 64 位 INTEGER 对齐,且 pgx 回 int64);
//   - 自增主键 → bigint GENERATED BY DEFAULT AS IDENTITY(BY DEFAULT 以便导入显式 id,
//     导入后须 setval 推进序列 —— 见 cmd/gwmigrate)。
const schemaVersion = 16

